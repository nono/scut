// Command genskill writes skills/scut/SKILL.md and docs/coverage.md from the
// scut command tree, and internal/cli/storyfields_gen.go from the v4 spec.
// It copies the "Not supported" list of skill_head.md into README.md, and
// writes there a table of each command and the operations it calls that write
// to Shortcut.
// With -check it writes nothing and exits 1 if a file differs.
package main

import (
	_ "embed"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	"github.com/spf13/cobra"
	"github.com/spf13/pflag"

	"github.com/nono/scut/internal/cli"
)

const (
	skillPath    = "skills/scut/SKILL.md"
	coveragePath = "docs/coverage.md"
	fieldsPath   = "internal/cli/storyfields_gen.go"
	specPath     = "api/shortcut.openapi.json"
	readmePath   = "README.md"
)

// The README lines between beginMark and endMark come from skill_head.md;
// the lines between permsMark and permsEnd come from the command tree.
const (
	beginMark = "<!-- begin: generated by make skill from skill_head.md -->"
	endMark   = "<!-- end: generated by make skill from skill_head.md -->"
	permsMark = "<!-- begin: generated by make skill from the command tree -->"
	permsEnd  = "<!-- end: generated by make skill from the command tree -->"
)

//go:embed skill_head.md
var skillHead string

const description = "Use when a task reads or changes Shortcut stories, epics, comments, links or attachments: " +
	"a story ID such as sc-1234, an app.shortcut.com URL, a git branch with sc-NNNN in it, a ticket or bug to file, " +
	"a sub-task, a state change such as \"move it to In Review\", a Shortcut doc, or the branch name of a story."

// localWrites are commands that call only GET operations but write the
// keyring: they stay out of allowed-tools. A command with an --out flag, or
// with no ops annotation (cache clear), stays out too, with no entry here.
var localWrites = map[string]bool{
	"auth login": true,
}

// localReads are commands that call no operation and only read: the only
// commands with no ops annotation that allowed-tools lists. A new command
// with no annotation stays out, so that it asks for permission.
var localReads = map[string]bool{
	"spec": true, // reads the embedded spec
}

// shortcutWrites returns the operations of c that write to Shortcut: each
// one that is not GET, and for scut api ("*") any operation.
func shortcutWrites(c *cobra.Command, spec specInfo) []string {
	var writes []string
	for _, op := range cli.Ops(c) {
		switch {
		case op == "*":
			writes = append(writes, "any operation; a DELETE needs `--yes`")
		case spec.methods[op] != "GET":
			writes = append(writes, "`"+op+"`")
		}
	}
	return writes
}

// allowed reports if allowed-tools lists c: it writes nothing other than the
// cache, and it has an ops annotation or is a local read. A rule matches the
// start of the command, so it cannot leave out a flag: a command with --out,
// which writes a file at a path that the caller gives, is not allowed.
func allowed(c *cobra.Command, spec specInfo) bool {
	p := cmdPath(c)
	return !localWrites[p] && c.Flags().Lookup("out") == nil && len(shortcutWrites(c, spec)) == 0 &&
		(len(cli.Ops(c)) > 0 || localReads[p])
}

// allowedTools is the allowed-tools value: the usage commands and each
// allowed command, so that an agent can read without a permission prompt
// and each write still asks.
func allowedTools(root *cobra.Command, spec specInfo) string {
	rules := []string{"Bash(scut usage:*)"}
	for _, c := range root.Commands() {
		if c.HasSubCommands() {
			rules = append(rules, "Bash(scut "+c.Name()+" usage:*)")
		}
	}
	for _, c := range leafCommands(root) {
		if allowed(c, spec) {
			rules = append(rules, "Bash(scut "+cmdPath(c)+":*)")
		}
	}
	sort.Strings(rules)
	return strings.Join(rules, ", ")
}

func frontmatter(root *cobra.Command, spec specInfo) string {
	// Quoted: a plain YAML value cannot hold ": ". A Go quoted string is a valid YAML double-quoted string.
	return "---\nname: scut\ndescription: " + strconv.Quote(description) +
		"\nallowed-tools: " + strconv.Quote(allowedTools(root, spec)) + "\n---\n\n"
}

func main() {
	env := cli.Env{Getenv: func(string) string { return "" }}
	os.Exit(run(os.Args[1:], os.Stderr, cli.NewRoot(env)))
}

func run(args []string, stderr io.Writer, root *cobra.Command) int {
	fs := flag.NewFlagSet("genskill", flag.ContinueOnError)
	fs.SetOutput(stderr)
	check := fs.Bool("check", false, "exit 1 if a generated file differs")
	dir := fs.String("root", ".", "repository root")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	spec, err := readSpec(filepath.Join(*dir, specPath))
	if err != nil {
		_, _ = fmt.Fprintln(stderr, "genskill:", err)
		return 1
	}
	cov, err := coverageText(root, spec)
	if err != nil {
		_, _ = fmt.Fprintln(stderr, "genskill:", err)
		return 1
	}
	readme, err := os.ReadFile(filepath.Join(*dir, readmePath))
	if err != nil {
		_, _ = fmt.Fprintln(stderr, "genskill:", err)
		return 1
	}
	readmeNew, err := readmeText(string(readme), permissionsText(root, spec))
	if err != nil {
		_, _ = fmt.Fprintln(stderr, "genskill:", err)
		return 1
	}
	files := []struct{ path, text string }{
		{skillPath, skillText(root, spec)},
		{coveragePath, cov},
		{fieldsPath, storyFieldsText(spec)},
		{readmePath, readmeNew},
	}
	var stale []string
	for _, f := range files {
		full := filepath.Join(*dir, f.path)
		if *check {
			if b, err := os.ReadFile(full); err != nil || string(b) != f.text {
				stale = append(stale, f.path)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			_, _ = fmt.Fprintln(stderr, "genskill:", err)
			return 1
		}
		if err := os.WriteFile(full, []byte(f.text), 0o644); err != nil {
			_, _ = fmt.Fprintln(stderr, "genskill:", err)
			return 1
		}
	}
	if len(stale) > 0 {
		_, _ = fmt.Fprintf(stderr, "differs from the generated text, run make skill: %s\n", strings.Join(stale, ", "))
		return 1
	}
	return 0
}

// skipCmd reports commands that are not part of the reference.
func skipCmd(c *cobra.Command) bool {
	switch c.Name() {
	case "usage", "help", "completion":
		return true
	}
	return c.Hidden
}

// leafCommands returns the leaf commands sorted by path.
func leafCommands(root *cobra.Command) []*cobra.Command {
	var out []*cobra.Command
	var walk func(c *cobra.Command)
	walk = func(c *cobra.Command) {
		for _, s := range c.Commands() {
			switch {
			case skipCmd(s):
			case s.HasSubCommands():
				walk(s)
			default:
				out = append(out, s)
			}
		}
	}
	walk(root)
	sort.Slice(out, func(i, j int) bool { return cmdPath(out[i]) < cmdPath(out[j]) })
	return out
}

// cmdPath returns the command path without the root name.
func cmdPath(c *cobra.Command) string {
	return strings.TrimPrefix(c.CommandPath(), c.Root().Name()+" ")
}

func skillText(root *cobra.Command, spec specInfo) string {
	var b strings.Builder
	b.WriteString(frontmatter(root, spec))
	b.WriteString(skillHead)
	for _, c := range leafCommands(root) {
		fmt.Fprintf(&b, "- `%s`", cmdPath(c))
		if _, a, ok := strings.Cut(c.Use, " "); ok {
			fmt.Fprintf(&b, " `%s`", a)
		}
		fmt.Fprintf(&b, " %s.", strings.TrimSuffix(c.Short, "."))
		var flags []string
		c.LocalFlags().VisitAll(func(f *pflag.Flag) {
			if f.Hidden {
				return
			}
			s := "--" + f.Name
			if _, ok := f.Value.(pflag.SliceValue); ok {
				s += " …" // repeatable
			}
			flags = append(flags, s)
		})
		sort.Strings(flags)
		if len(flags) > 0 {
			fmt.Fprintf(&b, " Flags: %s.", strings.Join(flags, ", "))
		}
		b.WriteString("\n")
	}
	return b.String()
}

// opsByCommand maps each operationId to the sorted command paths that call it.
// The "*" of scut api is left out.
func opsByCommand(root *cobra.Command) map[string][]string {
	m := map[string][]string{}
	for _, c := range leafCommands(root) {
		for _, op := range cli.Ops(c) {
			if op != "*" {
				m[op] = append(m[op], cmdPath(c))
			}
		}
	}
	for _, cmds := range m {
		sort.Strings(cmds)
	}
	return m
}

type specInfo struct {
	total       int
	methods     map[string]string // operationId to its HTTP method, in upper case
	storyFields []string          // the top-level properties of the Story schema, sorted
}

func readSpec(path string) (specInfo, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return specInfo{}, err
	}
	var doc struct {
		Paths      map[string]map[string]json.RawMessage `json:"paths"`
		Components struct {
			Schemas struct {
				Story struct {
					Properties map[string]json.RawMessage `json:"properties"`
				} `json:"Story"`
			} `json:"schemas"`
		} `json:"components"`
	}
	if err := json.Unmarshal(b, &doc); err != nil {
		return specInfo{}, fmt.Errorf("%s: %w", path, err)
	}
	s := specInfo{methods: map[string]string{}}
	for _, item := range doc.Paths {
		for method, raw := range item {
			var op struct {
				ID string `json:"operationId"`
			}
			if json.Unmarshal(raw, &op) == nil && op.ID != "" {
				s.methods[op.ID] = strings.ToUpper(method)
			}
		}
	}
	s.total = len(s.methods)
	for name := range doc.Components.Schemas.Story.Properties {
		s.storyFields = append(s.storyFields, name)
	}
	if len(s.storyFields) == 0 {
		return specInfo{}, fmt.Errorf("%s: no Story schema properties", path)
	}
	sort.Strings(s.storyFields)
	return s, nil
}

// storyFieldsText is the Go file that lists the Story properties, for --fields.
func storyFieldsText(spec specInfo) string {
	var b strings.Builder
	b.WriteString("// Code generated by genskill from " + specPath + "; DO NOT EDIT.\n\n")
	b.WriteString("package cli\n\n")
	b.WriteString("// apiStoryFields are the top-level properties of the Story schema.\n")
	b.WriteString("var apiStoryFields = []string{\n")
	for _, f := range spec.storyFields {
		fmt.Fprintf(&b, "\t%q,\n", f)
	}
	b.WriteString("}\n")
	return b.String()
}

func coverageText(root *cobra.Command, spec specInfo) (string, error) {
	ops := opsByCommand(root)
	ids := make([]string, 0, len(ops))
	for id := range ops {
		if _, ok := spec.methods[id]; !ok {
			return "", fmt.Errorf("operationId %q is not in %s", id, specPath)
		}
		ids = append(ids, id)
	}
	sort.Strings(ids)
	var b strings.Builder
	b.WriteString("# Endpoint coverage\n\n")
	b.WriteString("Generated by `make skill`. Do not edit.\n\n")
	fmt.Fprintf(&b, "Commands call %d of %d v4 operations. `scut api` can call any operation.\n\n", len(ids), spec.total)
	b.WriteString("| operationId | Commands |\n|---|---|\n")
	for _, id := range ids {
		fmt.Fprintf(&b, "| %s | %s |\n", id, "`"+strings.Join(ops[id], "`, `")+"`")
	}
	return b.String(), nil
}

// notSupported returns the list of the "Not supported" section of skill_head.md.
func notSupported() string {
	_, sec, _ := strings.Cut(skillHead, "## Not supported\n")
	sec, _, _ = strings.Cut(sec, "\n## ")
	return strings.TrimSpace(sec)
}

// permissionsText is the README table that tells, for each command, the
// operations that write to Shortcut (the operations that are not GET), and
// if the skill's allowed-tools lists it.
// coverageText has already checked that each operationId is in the spec.
func permissionsText(root *cobra.Command, spec specInfo) string {
	var b strings.Builder
	b.WriteString("| Command | Writes to Shortcut | In the skill's allowed-tools |\n|---|---|---|\n")
	for _, c := range leafCommands(root) {
		w := "no"
		if writes := shortcutWrites(c, spec); len(writes) > 0 {
			w = strings.Join(writes, ", ")
		}
		in := "no"
		if allowed(c, spec) {
			in = "yes"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s |\n", cmdPath(c), w, in)
	}
	return strings.TrimSuffix(b.String(), "\n")
}

// readmeText returns readme with the lines between each pair of markers
// replaced: the "Not supported" list, then perms.
func readmeText(readme, perms string) (string, error) {
	for _, sec := range []struct{ begin, end, text string }{
		{beginMark, endMark, notSupported()},
		{permsMark, permsEnd, perms},
	} {
		head, rest, ok := strings.Cut(readme, sec.begin)
		_, tail, ok2 := strings.Cut(rest, sec.end)
		if !ok || !ok2 {
			return "", fmt.Errorf("%s: no %q ... %q markers", readmePath, sec.begin, sec.end)
		}
		readme = head + sec.begin + "\n" + sec.text + "\n" + sec.end + tail
	}
	return readme, nil
}
